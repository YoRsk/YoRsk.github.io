"""
Maple Mono NF CN —— 按 unicode-range 切片。

为什么不再用单文件
    单文件 1,498,932 B（1.43 MiB）意味着**任何**出现中文的页面都要完整下载
    1.43 MiB，其中绝大部分汉字这一页根本用不到。
    切成多片后浏览器只下载页面真正命中的那几片，典型中文页实测降到 ~200 KiB。

分块依据（关键取舍）
    ⚠️ 按**使用频率序**分块，不是按码点序。
    GB2312 的码点顺序是「一级字拼音序 + 二级字部首序」，跟使用频率无关；
    按码点等分的话，一页用到的字会均匀散落在所有片里，几乎每片都被命中，
    等于没切（实测：码点序 111 片时截图文命中 94 片 / 1091 KiB）。

    频率表来源：jieba 简体中文词频词典（词频按词长摊到每个字），
    叠加少量中文维基正文做平滑。之所以不用 Rime essay.txt：那份语料是繁体
    为主的文学语料，简体常用字被严重低估（国=100、个=0、们=0、为=0），
    用它排序会把大量常用简体字误判成生僻字，切片命中数直接翻倍。

    频率表缓存：scripts/maple-hanzi-freq.txt（6763 字，按频率降序）。
    有缓存就直接用（离线可复现）；没有才去下载 jieba 词典重建并落盘。

    片边界：在「频率序」上取连续区间，用坐标下降在站点现有正文
    （src/content/**/*.md）上最小化「命中字节数」加权和。
    结构本身是频率序的（可推广），只有边界位置参考了现有正文。

静态字重（沿用 scripts/subset-maple-font.py 的结论，不要改回可变轴）
    GB2312 全集 + 可变轴 = 4.25 MiB；静态实例化 wght=400 = 1.43 MiB。
    保留可变轴要压进 1.5 MiB 只能砍到 ~2000 汉字，缺字严重。
    代价：中文无连续字重变化，粗体由浏览器合成。

用法
    python scripts/split-maple-font.py --plan            # 只出方案，不生成
    python scripts/split-maple-font.py --font <ttf>      # 生成切片 + 回填 CSS
"""

