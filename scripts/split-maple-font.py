def is_han(ch: str) -> bool:
    """判断是否为 CJK 统一汉字。"""
    return "CJK UNIFIED" in unicodedata.name(ch, "")


# 复用的临时字符集文件（只写这一个，不逐片新建/删除：
# 99 片会产生 99 次 unlink，触发 safe-delete 的批量删除拦截）
CHARSET_TMP = Path(__import__("tempfile").gettempdir()) / "maple-slice.charset.txt"


def subset(src_ttf: Path, chars: set[str], out: Path) -> None:
    """pyftsubset 参数与 scripts/subset-maple-font.py 的 subset() 完全一致，
    唯一区别是字符集写到一个复用的临时文件，不逐片创建再删除。"""
    CHARSET_TMP.write_text("".join(sorted(chars)), encoding="utf-8")
    cmd = [
        sys.executable,
        "-m",
        "fontTools.subset",
        str(src_ttf),
        f"--text-file={CHARSET_TMP}",
        f"--output-file={out}",
        "--flavor=woff2",
        "--drop-tables+=GSUB,GPOS",
        "--layout-features=",
        "--no-hinting",
        "--desubroutinize",
        "--notdef-outline",
        "--notdef-glyph",
        "--recommended-glyphs",
        "--name-IDs=*",
        "--name-legacy",
        "--no-prune-unicode-ranges",
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"pyftsubset 失败：\n{result.stderr}")


# ---------------------------------------------------------------- 频率表
def build_freq_from_corpus() -> dict[str, float]:
    """从 jieba 简体词频词典推导字频（词频按词长摊到每个字）。"""
    import urllib.request

    tmp = Path(__import__("tempfile").gettempdir()) / "jieba_dict.txt"
    if not tmp.is_file():
        print(f"[INFO] 下载 jieba 词典：{JIEBA_DICT_URL}", flush=True)
        with urllib.request.urlopen(JIEBA_DICT_URL, timeout=180) as resp:
            tmp.write_bytes(resp.read())
    freq: dict[str, float] = {}
    for ln in tmp.read_text(encoding="utf-8").splitlines():
        parts = ln.split(" ")
        if len(parts) < 2:
            continue
        word, raw = parts[0], parts[1]
        try:
            value = float(raw)
        except ValueError:
            continue
        for ch in word:
            if is_han(ch):
                freq[ch] = freq.get(ch, 0.0) + value
    return freq


def load_freq_order(hanzi: set[str]) -> list[str]:
    """返回按使用频率降序排列的汉字列表（含缓存读写）。"""
    if FREQ_CACHE.is_file():
        order: list[str] = []
        for ln in FREQ_CACHE.read_text(encoding="utf-8").splitlines():
            ch = ln.split("\t")[0]
            if ch:
                order.append(ch)
        if set(order) == hanzi:
            print(f"[INFO] 使用缓存频率表：{FREQ_CACHE.name}（{len(order)} 字）")
            return order
        print("[WARN] 缓存频率表与当前 GB2312 字集不一致，重建")

    freq = build_freq_from_corpus()
    for ch in hanzi:
        freq.setdefault(ch, 0.0)
    floor = min((v for v in freq.values() if v > 0), default=1.0) / 1000.0
    order = sorted(hanzi, key=lambda c: (-max(freq[c], floor), c))
    FREQ_CACHE.write_text(
        "\n".join(f"{c}\t{freq[c]:.0f}" for c in order), encoding="utf-8"
    )
    print(f"[INFO] 已重建并缓存频率表：{FREQ_CACHE.name}（{len(order)} 字）")
    return order


# ---------------------------------------------------------------- 切片优化
class PageModel:
    """站点正文的汉字集合（已换算成「频率序」上的位置）。"""

    def __init__(self, name: str, ranks: list[int], weight: float) -> None:
        self.name = name
        self.ranks = sorted(ranks)
        self.weight = weight


def collect_pages(order: list[str]) -> list[PageModel]:
    """扫描 src/content/**/*.md，把每篇正文的汉字映射成频率序位置。"""
    pos = {c: i for i, c in enumerate(order)}
    models: list[PageModel] = []
    for path in sorted((REPO / "src" / "content").rglob("*.md")):
        text = path.read_text(encoding="utf-8")
        ranks = sorted({pos[c] for c in re.findall(r"[㐀-鿿]", text) if c in pos})
        if not ranks:
            continue
        models.append(
            PageModel(str(path.relative_to(REPO)), ranks, float(len(ranks)))
        )
    return models


def _hits(ranks: list[int], lo: int, hi: int) -> bool:
    """[lo, hi) 内是否命中该页的任一汉字。"""
    idx = bisect.bisect_left(ranks, lo)
    return idx < len(ranks) and ranks[idx] < hi


def chunk_bytes(lo: int, hi: int, extra: float = 0.0) -> float:
    """一片的体积估计：固定开销 + 该频率序号区间的累计字成本。"""
    return extra + CHUNK_OVERHEAD + (COST_PREFIX[hi] - COST_PREFIX[lo])


def objective(
    bounds: list[int], pages: list[PageModel], core_bytes: float
) -> float:
    """加权命中字节数：第 0 片（符号核心）恒计入。"""
    total = 0.0
    for page in pages:
        cost = core_bytes + (COST_PREFIX[bounds[1]] - COST_PREFIX[bounds[0]])
        for k in range(1, len(bounds) - 1):
            if _hits(page.ranks, bounds[k], bounds[k + 1]):
                cost += chunk_bytes(bounds[k], bounds[k + 1])
        total += page.weight * cost
    return total


def _local_cost(pages: list[PageModel], lo: int, hi: int, core: float) -> float:
    """区间 [lo, hi) 作为一片时对所有页的加权代价（core 只有第 0 片才有）。"""
    acc = 0.0
    for page in pages:
        if core > 0.0 or _hits(page.ranks, lo, hi):
            acc += page.weight * (core + chunk_bytes(lo, hi))
    return acc


def _greedy_bounds(
    n_chunks: int,
    pages: list[PageModel],
    core_bytes: float,
    n: int,
    max_bytes: float = MAX_CHUNK_KIB * 1024,
    tail_chunks: int = TAIL_CHUNKS,
) -> list[int]:
    """频率序分块：体积上限预切 + 贪心切空档 + 尾部生僻字区等分。

    硬约束：任何一片的估算体积 <= max_bytes。做法是先用上限沿频率序预切一刀，
    之后所有切分只会让片更小，所以约束恒成立。

    【为什么尾部要单独等分，不能交给贪心】
    贪心切的是「正文用到的字之间的空档」，而尾部生僻字区（最后一个被用到的字
    之后）一个锚点都没有，贪心对那里无从下手。上一版就是因此留下了一片
    2856 字 / 653 KiB 的巨片：只要新文章出现一个字频 >=3908 的字就得多付
    653 KiB。这里显式把它等分成 tail_chunks 片，代价是这些片从贪心预算里扣。

    两种切法，都按真实代价差挑收益最大的一个：
      两刀 [lo,g_lo) + [g_lo,g_hi) + [g_hi,hi)：中间那片没有任何正文用到的字，
        于是整段不会被下载（这是省体积的主力，形成 2H+1 结构）。
      一刀切在「首锚点」或「末锚点之后」：把锚点边缘的大片无字区让出去。
        少了这一刀就会出事：某页只用了一个序号 3906 的生僻字，
        却要拖下一整片 1222 字 / 291 KiB。
    """
    anchors = sorted({r for p in pages for r in p.ranks})
    last = (anchors[-1] + 1) if anchors else n
    budget = n_chunks - tail_chunks - 1

    # 1) 沿频率序按体积上限预切（第 0 片还要算上符号核心）
    bounds = [0]
    i = 0
    while i < last:
        j = i + 1
        while j < last and chunk_bytes(i, j + 1, core_bytes if i == 0 else 0.0) <= max_bytes:
            j += 1
        bounds.append(j)
        i = j
    bounds.append(last)

    # 2) 贪心切空档，直到用满预算
    while True:
        best: tuple[float, int, int, int, int] | None = None
        for k in range(len(bounds) - 1):
            lo, hi = bounds[k], bounds[k + 1]
            core0 = core_bytes if k == 0 else 0.0
            before = _local_cost(pages, lo, hi, core0)
            idx = bisect.bisect_left(anchors, lo)
            sub = []
            j = idx
            while j < len(anchors) and anchors[j] < hi:
                sub.append(anchors[j])
                j += 1
            candidates: list[tuple[int, int, int]] = []
            if sub:
                if sub[0] - lo >= 1:
                    candidates.append((1, sub[0], sub[0]))
                if hi - sub[-1] - 1 >= 1:
                    candidates.append((1, sub[-1] + 1, sub[-1] + 1))
            for i in range(len(sub) - 1):
                if sub[i + 1] - sub[i] - 1 >= 1:
                    candidates.append((2, sub[i] + 1, sub[i + 1]))
            for cuts, x1, x2 in candidates:
                if len(bounds) - 1 + cuts > budget:
                    continue
                if cuts == 1:
                    after = _local_cost(pages, lo, x1, core0) + _local_cost(
                        pages, x1, hi, 0.0
                    )
                else:
                    after = _local_cost(pages, lo, x1, core0) + _local_cost(
                        pages, x2, hi, 0.0
                    )
                saving = before - after
                if saving > 1e-9 and (best is None or saving > best[0]):
                    best = (saving, cuts, k, x1, x2)
        if best is None:
            break
        _, cuts, k, x1, x2 = best
        if cuts == 1:
            bounds = bounds[: k + 1] + [x1] + bounds[k + 1 :]
        else:
            bounds = bounds[: k + 1] + [x1, x2] + bounds[k + 1 :]

    # 3) 尾部生僻字区（最后一个锚点之后）等分 tail_chunks 片
    if tail_chunks > 0 and last < n:
        span = n - last
        step = span / tail_chunks
        extra = sorted({last + int(round(step * t)) for t in range(1, tail_chunks)})
        bounds = sorted(set(bounds) | set(extra))
    if bounds[-1] != n:
        bounds = bounds + [n]
    return bounds


def optimize_bounds(
    n_chunks: int,
    pages: list[PageModel],
    core_bytes: float,
    n: int,
    max_bytes: float = MAX_CHUNK_KIB * 1024,
    tail_chunks: int = TAIL_CHUNKS,
) -> list[int]:
    """在频率序上求切点（体积上限预切 + 贪心切空档 + 尾部等分）。

    刻意不接坐标下降：坐标下降会把边界继续往「现有正文的空档」上贴，
    训练集内更优、泛化更差。现在的结构对任意文章的表现是可预期的：
    最坏也就是命中全部含正文用字的片，不会踩到 653 KiB 那种悬崖。

    注意 max_bytes 是「模型估算」的上限，而模型对大片的实测值偏低约 7%
    （估算 194 KiB 的片落盘是 207 KiB），所以默认值留了余量。
    """
    return _greedy_bounds(n_chunks, pages, core_bytes, n, max_bytes, tail_chunks)


def random_sample_hits(
    bounds: list[int],
    pages: list[PageModel],
    freq_values: list[float],
    size: int = 361,
    trials: int = 400,
    seed: int = 20261019,
) -> float:
    """泛化指标：按字频加权随机抽 size 个不同汉字，返回命中字节的中位数。

    抽样方法（确定性，可复现）：以字频为权重做有放回抽样，直到凑够 size 个
    不同的字；重复 trials 次取中位数。这模拟「一篇全新文章会用到哪些字」，
    不依赖现有任何一篇正文，用来证明分块没有过拟合。
    """
    import random

    n = len(freq_values)
    rng = random.Random(seed)
    values: list[float] = []
    for _ in range(trials):
        seen: set[int] = set()
        while len(seen) < size:
            seen.add(rng.choices(range(n), weights=freq_values, k=1)[0])
        ranks = sorted(seen)
        total = CHUNK_OVERHEAD + (COST_PREFIX[bounds[1]] - COST_PREFIX[bounds[0]])
        for k in range(1, len(bounds) - 1):
            if _hits(ranks, bounds[k], bounds[k + 1]):
                total += chunk_bytes(bounds[k], bounds[k + 1])
        values.append(total)
    values.sort()
    return values[len(values) // 2]


# ---------------------------------------------------------------- unicode-range
def build_unicode_range(chars: set[str], covered: set[int], max_gap: int = 64) -> str:
    """生成 unicode-range。

    允许跨过「未被任何切片覆盖」的码位合并成区间：按 CSS 字体匹配规则，
    若命中的 @font-face 没有该码位的字形，浏览器会继续往后找兜底字体，
    与本方案（本来也没这个字形）表现一致。
    但绝不跨过别的切片拥有的码位，否则会抢走别的片的字形导致缺字。
    """
    codes = sorted(ord(c) for c in chars)
    runs: list[list[int]] = []
    for code in codes:
        if runs and code == runs[-1][1] + 1:
            runs[-1][1] = code
        else:
            runs.append([code, code])
    merged: list[list[int]] = [runs[0]]
    for run in runs[1:]:
        prev = merged[-1]
        gap_lo, gap_hi = prev[1] + 1, run[0] - 1
        if gap_hi < gap_lo:
            prev[1] = run[1]
            continue
        if gap_hi - gap_lo + 1 > max_gap:
            merged.append(run)
            continue
        if any(c in covered for c in range(gap_lo, gap_hi + 1)):
            merged.append(run)
            continue
        prev[1] = run[1]
    return ", ".join(
        f"U+{lo:04X}" if lo == hi else f"U+{lo:04X}-{hi:04X}" for lo, hi in merged
    )


# ---------------------------------------------------------------- 主流程
def collect_symbol_sets(
    gb_chars: set[str],
) -> tuple[dict[str, set[str]], set[str]]:
    """把非汉字字符拆成 4 个符号片，返回（片名->字符集, 全部符号集）。"""
    hanzi = {c for c in gb_chars if is_han(c)}
    gb_sym = {c for c in gb_chars if not is_han(c)}

    def rng(lo: int, hi: int) -> set[str]:
        return {chr(c) for c in range(lo, hi + 1) if unicodedata.category(chr(c)) != "Cn"}

    latin = rng(0x0020, 0x007E) | rng(0x00A0, 0x00FF)
    # 全角块里中文排版真正用得到的就这些：！＂＃＄％＆＇（）＊＋，－．／
    # ０-９ ：；＜＝＞？＠ ［＼］＾＿｀ ｛｜｝～
    # 其余（Ａ-Ｚ、ａ-ｚ、半角片假名、￠￡￥…）单独成片，用到才下载 —— 核心片
    # 是每一页都要下的，能省 1 字就省 1 字。
    fullwidth = rng(0xFF00, 0xFFEF)
    essential_fullwidth = {chr(c) for c in list(range(0xFF01, 0xFF21)) + list(range(0xFF3B, 0xFF41)) + list(range(0xFF5B, 0xFF5F))}
    core = (
        rng(0x2010, 0x203B)          # 通用标点 – — ‘ ’ “ ” … ‰
        | set(subset_mod.EXTRA_CHARS)  # € ℃ ℉ ™
        | rng(0x3000, 0x303F)        # CJK 标点 、 。 《 》 【 】
        | (fullwidth & essential_fullwidth)
    )
    # 箭头单独成片：正文里出现「→」的概率远高于出现 ≤ ≥ ∞ 的概率，
    # 合成一片的话一篇只用了一个 → 的文章要把 357 个字形（13.9 KiB）整片拖下来。
    # 按 Unicode 区块语义拆（箭头 vs 数学运算符/几何图形），不是照着现有正文挑字。
    arrow = rng(0x2190, 0x21FF)
    math = rng(0x2200, 0x22FF) | rng(0x25A0, 0x25FF)
    arrow -= core
    math -= core | arrow
    latin -= core
    fullwidth -= core | arrow | math | latin
    gb_sym -= core | arrow | math | latin | fullwidth
    groups = {
        "core": core,              # 恒被下载：中文排版必备
        "latin": latin,            # 拉丁：平日由 Google Sans Code 顶掉，几乎不下载
        "fullwidth": fullwidth,    # 全角拉丁 / 半角片假名 / 全角货币符号
        "arrow": arrow,            # 箭头 U+2190–21FF
        "math": math,              # 数学运算符 U+2200–22FF + 几何图形 U+25A0–25FF
        "gbsym": gb_sym,           # GB2312 符号区（假名、希腊、序号、制表符等）
    }
    return groups, hanzi


def main() -> int:
    parser = argparse.ArgumentParser(description="Maple Mono NF CN unicode-range 切片")
    parser.add_argument("--font", type=Path, help="源可变 TTF（MapleMono-NF-CN[wght].ttf）")
    parser.add_argument("--chunks", type=int, default=116, help="汉字切片数（不含 4 个符号片）")
    parser.add_argument(
        "--max-chunk-kib", type=float, default=MAX_CHUNK_KIB, help="单片体积硬上限（KiB）"
    )
    parser.add_argument(
        "--tail-chunks", type=int, default=TAIL_CHUNKS, help="尾部生僻字区等分片数"
    )
    parser.add_argument("--plan", action="store_true", help="只出方案与预估，不生成文件")
    parser.add_argument("--no-css", action="store_true", help="生成切片但不回填 global.css")
    parser.add_argument(
        "--force", action="store_true", help="强制重新生成已存在的切片"
    )
    args = parser.parse_args()

    gb_chars = subset_mod.decode_gb2312_range(0xA1, 0xFE)
    symbol_groups, hanzi = collect_symbol_sets(gb_chars)
    print(f"[INFO] GB2312 汉字 {len(hanzi)}，符号区 {len(symbol_groups['gbsym'])}")

    order = load_freq_order(hanzi)
    pages = collect_pages(order)
    total_weight = sum(p.weight for p in pages) or 1.0
    for p in pages:
        print(f"[INFO] 正文 {p.name}: 不同汉字 {len(p.ranks)}，频率序范围 [{p.ranks[0]}, {p.ranks[-1]}]")

    n = len(order)
    COST_PREFIX.clear()
    acc = 0.0
    COST_PREFIX.append(0.0)
    for r in range(n):
        acc += HANZI_BASE_COST + HANZI_SLOPE_COST * (r / n)
        COST_PREFIX.append(acc)
    core_bytes = SYMBOL_BYTES_PER_CHAR * len(symbol_groups["core"])
    print(
        f"[INFO] 符号核心估算 {core_bytes / 1024:.1f} KiB"
        f"（{len(symbol_groups['core'])} 字形，实测单片 25,884 B）"
    )

    freq_map: dict[str, float] = {}
    for ln in FREQ_CACHE.read_text(encoding="utf-8").splitlines():
        if ln.strip():
            ch, val = ln.split("\t")
            freq_map[ch] = float(val)
    freq_values = [max(freq_map.get(c, 0.0), 1e-9) for c in order]

    print("\n[PLAN] 片数 -> 各页预估命中 / 最大单片 / 随机抽样中位数")
    print(
        f"{'片数':>5} {'最大片KiB':>10} {'随机中位KiB':>12} "
        + " ".join(f"{Path(p.name).name[:12]:>13}" for p in pages)
    )
    chosen: list[int] = []
    chosen_n = 0
    for n_chunks in (96, 110, 116, 117):
        bounds = optimize_bounds(
            n_chunks, pages, core_bytes, n, args.max_chunk_kib * 1024, args.tail_chunks
        )
        sizes = [chunk_bytes(bounds[k], bounds[k + 1], core_bytes if k == 0 else 0.0)
                 for k in range(len(bounds) - 1)]
        cells = []
        for p in pages:
            cost = chunk_bytes(bounds[0], bounds[1], core_bytes)
            hits = 1
            for k in range(1, len(bounds) - 1):
                if _hits(p.ranks, bounds[k], bounds[k + 1]):
                    cost += chunk_bytes(bounds[k], bounds[k + 1])
                    hits += 1
            cells.append(f"{hits:>3}片 {cost / 1024:>7.1f}K")
        print(
            f"{n_chunks:>5} {max(sizes) / 1024:>10.1f} "
            f"{random_sample_hits(bounds, pages, freq_values) / 1024:>12.1f} "
            + " ".join(f"{c:>13}" for c in cells)
        )
        if n_chunks == args.chunks:
            chosen, chosen_n = bounds, n_chunks
    print("  （上表为模型预估，落盘后的真实值见下方 [CHECK]）")
    if not chosen:
        chosen = optimize_bounds(
            args.chunks, pages, core_bytes, n, args.max_chunk_kib * 1024, args.tail_chunks
        )
        chosen_n = args.chunks

    sizes = [chosen[k + 1] - chosen[k] for k in range(len(chosen) - 1)]
    print(
        f"\n[PLAN] 采用 {chosen_n} 片：每片字数 min={min(sizes)} max={max(sizes)} "
        f"median={sorted(sizes)[len(sizes) // 2]}；"
        f"最大单片估算 {max(chunk_bytes(chosen[k], chosen[k + 1]) for k in range(len(chosen) - 1)) / 1024:.1f} KiB"
        f"（估算上限 {args.max_chunk_kib:.0f} KiB，实测会再高约 7%）"
    )
    if args.plan:
        return 0
    if not args.font:
        print("[FATAL] 需要 --font 指定源可变 TTF", file=sys.stderr)
        return 1
    if not args.font.is_file():
        print(f"[FATAL] 源字体不存在：{args.font}", file=sys.stderr)
        return 1

    # ---- 实例化静态 wght=400（一次性）----
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer

    static_ttf = Path(__import__("tempfile").gettempdir()) / "maple-mono-nf-cn-wght400.ttf"
    if not static_ttf.is_file():
        print("[INFO] 实例化到 wght=400 ...", flush=True)
        inst = instancer.instantiateVariableFont(
            TTFont(args.font), {"wght": 400}, inplace=False, updateFontNames=False
        )
        inst.save(static_ttf)
    print(f"[INFO] 静态源字体：{static_ttf}（{static_ttf.stat().st_size:,} B）")

    # ---- 组装各片 ----
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    slices: list[tuple[str, set[str]]] = []
    for k in range(len(chosen) - 1):
        chars = set(order[chosen[k] : chosen[k + 1]])
        if k == 0:
            chars |= symbol_groups["core"]  # 符号核心并入第 0 片，省一次请求
        slices.append((f"maple-mono-nf-cn-{k:02d}.woff2", chars))
    for key in ("latin", "fullwidth", "arrow", "math", "gbsym"):
        if symbol_groups[key]:
            slices.append((f"maple-mono-nf-cn-{key}.woff2", set(symbol_groups[key])))

    covered: set[int] = set()
    for _, chars in slices:
        covered |= {ord(c) for c in chars}

    total_disk = 0
    for idx, (name, chars) in enumerate(slices, 1):
        out = FONT_DIR / name
        if not args.force and out.is_file() and out.stat().st_size > 0:
            pass
        else:
            subset(static_ttf, chars, out)
        size = out.stat().st_size
        total_disk += size
        if idx % 10 == 0 or idx == len(slices):
            print(f"[GEN] {idx}/{len(slices)} {name} {len(chars):>4} 字 {size:>8,} B", flush=True)

    # 片数会随参数变化，清理上一轮遗留的编号（否则 CSS 与磁盘对不上）
    keep = {name for name, _ in slices}
    stale = sorted(
        p for p in FONT_DIR.glob("maple-mono-nf-cn-*.woff2") if p.name not in keep
    )
    for p in stale:
        p.unlink()
    if stale:
        print(f"[GEN] 清理上一轮遗留切片 {len(stale)} 个")

    biggest_name, _ = max(slices, key=lambda s: (FONT_DIR / s[0]).stat().st_size)
    biggest_size = (FONT_DIR / biggest_name).stat().st_size
    limit = MAX_CHUNK_KIB * 1024
    print(f"\n[OK] 切片总数 {len(slices)}，磁盘总体积 {total_disk:,} B = {total_disk / 1024 / 1024:.2f} MiB")
    print(
        f"[OK] 最大单片 {biggest_name} = {biggest_size:,} B = {biggest_size / 1024:.1f} KiB"
        f"  —— 硬上限 {MAX_CHUNK_KIB:.0f} KiB：{'通过' if biggest_size <= limit else '超限！'}"
    )

    # ---- 实测各页命中 ----
    print("\n[CHECK] 真实命中（按落盘后的实际文件大小）")
    print("  说明：latin 片虽覆盖 ASCII/Latin-1，但 --font-app 里 Google Sans Code")
    print("        排在前面且自带这些字形，浏览器不会去下 Maple 的 latin 片，故单列。")
    for p in pages:
        text_chars = set((REPO / p.name).read_text(encoding="utf-8"))
        hit: list[tuple[str, int]] = []
        for name, chars in slices:
            if not (chars & text_chars):
                continue
            size = (FONT_DIR / name).stat().st_size
            hit.append((name, size))
        # 第 0 片含符号核心，中文页必中（正文里的 CJK 标点就在这一片）
        total = sum(s for _, s in hit)
        latin = sum(s for n, s in hit if n.endswith("-latin.woff2"))
        extras = sorted(
            n for n, _ in hit
            if n[len("maple-mono-nf-cn-"):-6] in {"latin", "fullwidth", "arrow", "math", "gbsym"}
        )
        print(
            f"  {p.name}\n"
            f"      命中 {len(hit)} 片 / {total:,} B = {total / 1024:.1f} KiB = {total / 1000:.1f} KB\n"
            f"      去掉 latin 片后 {total - latin:,} B = {(total - latin) / 1000:.1f} KB\n"
            f"      命中的符号片：{extras if extras else '无'}"
        )

    # ---- 生成 @font-face ----
    lines = [
        BEGIN_MARK,
        "/* 本段由 scripts/split-maple-font.py 生成，请勿手动编辑。 */",
    ]
    for name, chars in slices:
        lines.append("@font-face {")
        lines.append('  font-family: "Maple Mono NF CN";')
        lines.append(f'  src: url("/fonts/{name}") format("woff2");')
        lines.append(f"  unicode-range: {build_unicode_range(chars, covered)};")
        lines.append("  font-weight: 400;")
        lines.append("  font-style: normal;")
        lines.append("  font-display: swap;")
        lines.append("}")
    lines.append(END_MARK)
    block = "\n".join(lines)

    if args.no_css:
        print("\n[CSS]\n" + block)
        return 0

    css = GLOBAL_CSS.read_text(encoding="utf-8")
    if BEGIN_MARK not in css or END_MARK not in css:
        print(f"[FATAL] {GLOBAL_CSS} 缺少标记注释，无法回填", file=sys.stderr)
        return 1
    head, rest = css.split(BEGIN_MARK, 1)
    _, tail = rest.split(END_MARK, 1)
    GLOBAL_CSS.write_text(head + block + tail, encoding="utf-8")
    print(f"[OK] 已回填 {GLOBAL_CSS.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
