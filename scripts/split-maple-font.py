# ---------------------------------------------------------------- 体积模型
# 用 scripts/subset-maple-font.py 之外的实测数据拟合（99 片落盘后回归得到）：
#   size = 1945 + 218.5·汉字数 + 34.8·Σ(频率序号/6763) + 58.9·符号数
# 三点与最初的朴素假设不同，且都对分块结论有决定性影响：
#   1) 每片固定开销约 1.9 KiB，不是空片的 948 B —— 小片 brotli 压缩率很差，
#      十几字的片实测 ~330 B/字，而千字大片只有 ~246 B/字。片数不是越多越好。
#   2) 汉字每字成本随「频率序号」上升：常用字笔画少、字形简单（~193 B/字），
#      生僻字笔画多（~246 B/字），所以高频片区天生更便宜。
#   3) 符号（~59 B/字）远便宜于汉字，值得单独成片而不是塞进每一片。
CHUNK_OVERHEAD = 1945.0         # 每片固定开销
# 单片体积硬上限：不允许再出现 653 KiB 那种巨片。
# 180 是「模型估算」口径；模型对大片实测偏低约 7%（估算 194 KiB 落盘 207 KiB），
# 所以估算上限取 180 KiB，落盘实测约 190 KiB，稳定落在 200 KiB 以内。
MAX_CHUNK_KIB = 180.0
TAIL_CHUNKS = 12                # 尾部生僻字区（无人用到的那段）等分成的片数
HANZI_BASE_COST = 218.5         # 频率序号 0 处的每字成本
HANZI_SLOPE_COST = 34.8         # 每字成本随序号线性增长的斜率
SYMBOL_BYTES_PER_CHAR = 58.9    # 符号每字成本

# 频率序上前 k 个字的累计成本，main() 里填充
COST_PREFIX: list[float] = []

BEGIN_MARK = "/* >>> MAPLE FONT FACES: AUTO-GENERATED BY scripts/split-maple-font.py >>> */"
END_MARK = "/* <<< MAPLE FONT FACES >>> */"

